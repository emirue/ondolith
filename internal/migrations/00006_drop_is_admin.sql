-- +goose Up

-- `users.is_admin` 을 지운다 (W2-01, NFR-303, NFR-308).
--
-- **⚠️ 되돌릴 수 없다.** Down 은 컬럼을 되살리지만 **값은 복원하지 못한다** —
-- 누가 관리자였는지는 이 컬럼이 아니라 `user_roles` 가 안다. 아래 Down 이
-- 전부 `false` 로 되살리는 이유가 그것이고, 그래서 이 릴리즈 이후로는
-- 이전 버전으로 되돌아갈 수 없다.
--
-- **왜 지우나.** 권한은 00002 의 RBAC(역할↔권한, D15)이 정한다. 이 컬럼은
-- Phase 0 의 잔재로, 지금은 **쓰이기만 하고 아무도 판정에 읽지 않는다** —
-- 설치가 `true` 를 넣고 00003 의 백필이 한 번 읽을 뿐이다.
--
-- 값을 쓰는데 아무도 안 읽는 컬럼이 가장 위험하다. 이름이 `is_admin` 이라
-- 권위 있어 보이므로, 나중에 누군가 `WHERE is_admin` 으로 관리자 판정을 하나
-- 짜 넣으면 **RBAC 이 관리하지 않는 권한 우회로**가 생긴다. 권한을 회수해도
-- 그 경로는 계속 통한다 (D15 4.3-1 이 캐싱을 금지하는 것과 같은 이유다).
--
-- **왜 지금인가.** D30 의 두 릴리즈 규칙: 릴리즈 N 에서 대체물을 넣고 양쪽을
-- 쓰고, N+1 에서 옛 컬럼을 지운다. N 은 v0.1.0 이었다.
--
-- **00003 의 백필은 그대로 둔다.** `WHERE u.is_admin` 은 마이그레이션 순서상
-- 여기보다 먼저 돌아 이미 역할을 부여한 뒤다. 옛 스키마에서 올라오는 사이트가
-- 관리자를 잃지 않는 유일한 경로이므로 지우면 안 된다.
ALTER TABLE users DROP COLUMN is_admin;

-- +goose Down

-- **값은 돌아오지 않는다.** 전부 false 로 되살아난다 — 이 컬럼이 관리자를
-- 뜻하던 시절의 정보는 이 시점에 이미 없다. 되돌리려면 `user_roles` 에서
-- admin 역할을 가진 계정을 손으로 찾아 다시 켜야 한다.
ALTER TABLE users ADD COLUMN is_admin boolean NOT NULL DEFAULT false;
